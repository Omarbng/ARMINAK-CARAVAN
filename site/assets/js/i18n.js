  var origText = new Map();
  var origPh   = new Map();
  var origData = new Map();

  function each(root, sel, fn) {
    Array.prototype.forEach.call(root.querySelectorAll(sel), fn);
  }

  function translate(root, ru) {
    each(root, '[data-i18n]', function (el) {
      if (!origText.has(el)) origText.set(el, el.textContent);
      var v = ru ? RU[el.getAttribute('data-i18n')] : origText.get(el);
      if (v != null) el.textContent = v;
    });

    each(root, '[data-i18n-ph]', function (el) {
      if (!origPh.has(el)) origPh.set(el, el.getAttribute('placeholder') || '');
      var v = ru ? RU[el.getAttribute('data-i18n-ph')] : origPh.get(el);
      if (v != null) el.setAttribute('placeholder', v);
    });

    /* Product name and grade are read off the card by the drawer. */
    each(root, '[data-product-key]', function (el) {
      if (!origData.has(el)) {
        origData.set(el, {
          p: el.getAttribute('data-product'),
          g: el.getAttribute('data-grade')
        });
      }
      var o = origData.get(el);
      var p = ru && RU[el.getAttribute('data-product-key')];
      var g = ru && RU[el.getAttribute('data-grade-key')];
      el.setAttribute('data-product', p || o.p);
      el.setAttribute('data-grade', g || o.g);
    });
  }

  function apply(lang) {
    current = lang === 'ru' ? 'ru' : 'en';
    document.documentElement.lang = current;
    translate(document, current === 'ru');

    each(document, '.lang__btn', function (b) {
      b.setAttribute('aria-pressed', String(b.getAttribute('data-lang') === current));
    });

    try { localStorage.setItem(STORE, current); } catch (e) { /* private mode */ }

    /* Dynamic renderers (the product page) re-render on this. */
    document.dispatchEvent(new CustomEvent('ac:lang', { detail: { lang: current } }));
  }

  /* Content injected after load (the drawer's spec table) re-translates here. */
  window.ACI18N = {
    retranslate: function (root) { translate(root || document, current === 'ru'); },
    current: function () { return current; }
  };

  function boot() {
    each(document, '.lang__btn', function (b) {
      b.addEventListener('click', function () { apply(b.getAttribute('data-lang')); });
    });

    var saved = null;
    try { saved = localStorage.getItem(STORE); } catch (e) {}
    apply(saved === 'ru' ? 'ru' : 'en');
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot);
  } else {
    boot();
  }
